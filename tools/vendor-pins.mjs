#!/usr/bin/env node
// tools/vendor-pins.mjs — emit the competitor-review pin table so a pin cannot live only in a gitignored directory.
//
// Why this exists (operator, 2026-10-28): "A pin step in the runbook's Do 2 that emits the header table
// automatically, so pins can't live only in a gitignored directory." The problem is structural: every
// competitor clone lives under `vendor/eval/`, which `.gitignore` excludes ("reference clones … must never
// enter the tree's history"), so the moment a review's HEAD+date+license exist only in the clone, they are
// one worktree sweep from gone. That already happened to me: the 2026-10-28 pointer had to carry the seven
// pins as a hand-typed table with the note "these pins live ONLY in this file", and hand-typed pins drift.
//
// So the pin becomes a GENERATED, TRACKED artifact (`docs/VENDOR-PINS.md`) plus a drift check:
//   node tools/vendor-pins.mjs --write docs/VENDOR-PINS.md    regenerate the tracked table from the live clones
//   node tools/vendor-pins.mjs --check                        fail if the tracked table no longer matches them
// `--check` also fails when the table is not TRACKED (`git ls-files`) or when it sits in an ignored path —
// the exact failure this exists to prevent, enforced rather than remembered.
//
// Do 2 of `docs/runbooks/competitor-review.md` uses `--format header`: it prints the review header block
// (HEAD · date · license · shallow · tag · manifest version · maturity placeholder · the question) so nothing
// is transcribed by hand, and it prints the command that produced every field. Claims must be reproducible
// by someone who does not have this session.
//
// What the tool deliberately does NOT do: judge maturity. `docs/SELFDEV.md` (2026-10-28) records three
// manifest versions that lie about it — OpenHands' root `package.json` says `1.34.0` while its release tag is
// `v1.9.0`, `hermes-agent`'s `pyproject.toml` says `0.0.0`, `oh-my-pi`'s `package.json` has no version. The
// tool prints them labelled UNRELIABLE and leaves `<judge>` in the maturity column.
//
//   node tools/vendor-pins.mjs                       markdown table for every vendor/eval/* clone (offline)
//   node tools/vendor-pins.mjs --tags                also fetch the latest remote tag (network)
//   node tools/vendor-pins.mjs --project <name>      restrict (repeatable)
//   node tools/vendor-pins.mjs --format table|header|json
//   node tools/vendor-pins.mjs --write <path>        rewrite the generated block in a tracked file
//   node tools/vendor-pins.mjs --check [<path>]      drift-check the tracked table (exit 1 on drift)
//
// Exit: 0 clean; 1 drift or a failed check; 2 usage / no clones.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_CLONE_DIR = "vendor/eval";
const DEFAULT_TABLE = "docs/VENDOR-PINS.md";
const BEGIN = (args) => `<!-- BEGIN GENERATED VENDOR PINS — generated by tools/vendor-pins.mjs (args: ${args}) — do not hand-edit -->`;
const END = "<!-- END GENERATED VENDOR PINS -->";
const BEGIN_RE = /<!-- BEGIN GENERATED VENDOR PINS — generated by tools\/vendor-pins\.mjs \(args: ([^)]*)\) — do not hand-edit -->/;

const USAGE = `usages:
  node tools/vendor-pins.mjs                       markdown table for every ${DEFAULT_CLONE_DIR}/* clone (offline)
  node tools/vendor-pins.mjs --tags                also fetch each project's latest remote tag (network)
  node tools/vendor-pins.mjs --project <name>      restrict to one project (repeatable)
  node tools/vendor-pins.mjs --format table|header|json   header = the review header block for competitor-review.md Do 2
  node tools/vendor-pins.mjs --write <path>        regenerate the generated block in a tracked file (default ${DEFAULT_TABLE})
  node tools/vendor-pins.mjs --check [<path>]      fail if the tracked table drifts from the clones, or is not tracked`;

class UsageError extends Error {}

function parseArgs(argv) {
	const opts = { tags: false, projects: [], format: "table", write: null, check: false, checkPath: DEFAULT_TABLE, clones: DEFAULT_CLONE_DIR };
	for (let i = 0; i < argv.length; i++) {
		const a = argv[i];
		if (a === "--tags") opts.tags = true;
		else if (a === "--project") {
			const v = argv[++i];
			if (!v) throw new UsageError("--project needs a name");
			opts.projects.push(v);
		} else if (a === "--format") {
			opts.format = argv[++i];
			if (!["table", "header", "json"].includes(opts.format)) throw new UsageError(`--format must be table|header|json (got "${opts.format}")`);
		} else if (a === "--write") {
			opts.write = argv[++i] ?? DEFAULT_TABLE;
		} else if (a === "--check") {
			opts.check = true;
			if (argv[i + 1] && !argv[i + 1].startsWith("--")) opts.checkPath = argv[++i];
		} else if (a === "--clones") {
			opts.clones = argv[++i];
			if (!opts.clones) throw new UsageError("--clones needs a directory");
		} else if (a === "--help" || a === "-h") opts.help = true;
		else throw new UsageError(`unknown argument: ${a}`);
	}
	return opts;
}

/** Run git and report the exit code honestly. `allowFail` is call-site documentation only: this never throws. */
function git(args, { allowFail = false } = {}) { // eslint-disable-line no-unused-vars
	const r = spawnSync("git", args, { cwd: ROOT, encoding: "utf8", timeout: 60_000 });
	// `ok` follows the exit code in BOTH modes — a wrapper that reports success for a failed call turns a
	// missing pin into a passing one.
	const out = (r.stdout ?? "").trim();
	if (r.status !== 0) return { ok: false, out, err: (r.stderr || `git ${args.join(" ")} exited ${r.status}`).trim() };
	return { ok: true, out, err: "" };
}

/** Every git clone directly under the vendoring directory. */
function discoverClones(dir) {
	const abs = join(ROOT, dir);
	if (!existsSync(abs)) return [];
	return readdirSync(abs)
		.filter((n) => {
			try {
				return statSync(join(abs, n)).isDirectory() && (existsSync(join(abs, n, ".git")));
			} catch {
				return false;
			}
		})
		.sort()
		.map((n) => `${dir}/${n}`);
}

const LICENSE_RULES = [
	["MIT", /Permission is hereby granted, free of charge/],
	["Apache-2.0", /Apache License[\s\S]{0,40}Version 2\.0/],
	["AGPL-3.0", /GNU AFFERO GENERAL PUBLIC LICENSE[\s\S]{0,80}Version 3/],
	["GPL-3.0", /GNU GENERAL PUBLIC LICENSE[\s\S]{0,80}Version 3/],
	["GPL-2.0", /GNU GENERAL PUBLIC LICENSE[\s\S]{0,80}Version 2/],
	["MPL-2.0", /Mozilla Public License Version 2\.0/],
	["ISC", /Permission to use, copy, modify, and\/?or distribute this software/],
	["BSD-3-Clause", /Redistributions in binary form[\s\S]*neither the name/i],
	["BSD-2-Clause", /Redistributions in binary form/],
	["Unlicense", /This is free and unencumbered software/],
];

/**
 * Read the license from the file, not from memory or a badge.
 *
 * The runbook's rule is "Check the license BEFORE borrowing — a copyleft or missing license is an escalation,
 * not a quiet copy", and `vendor/eval/` is gitignored, so a remembered licence is uncheckable. This returns the
 * matched signature and the path that carried it, so the claim is falsifiable inside the clone.
 */
function detectLicense(cloneRel) {
	const abs = join(ROOT, cloneRel);
	const names = readdirSync(abs).filter((n) => /^(license|copying)(\.md|\.txt)?$/i.test(n));
	if (names.length === 0) return { id: "NO LICENSE FILE", evidence: null, note: "ESCALATE before borrowing (runbook: a missing licence is an escalation, not a quiet copy)" };
	const first = names.sort()[0];
	const text = readFileSync(join(abs, first), "utf8");
	for (const [id, re] of LICENSE_RULES) {
		const m = text.match(re);
		if (m) return { id, evidence: `${cloneRel}/${first}`, note: `matched ${JSON.stringify(m[0].replace(/\s+/g, " ").slice(0, 48))}` };
	}
	return { id: "UNRECOGNISED", evidence: `${cloneRel}/${first}`, note: "read it by hand before borrowing" };
}

/**
 * Highest VERSION-LIKE tag by numeric-segment comparison — deliberately not `tail -1` (alphabetical) and
 * deliberately not "the max tag": a remote's tag set contains moving labels like `nightly` and
 * `test-simplify-docker-ci`, and a bare max picks those. Non-version tags are counted, not ranked.
 */
function latestTag(cloneRel) {
	const r = git(["-C", cloneRel, "ls-remote", "--tags", "origin"], { allowFail: true });
	if (!r.ok) return { tag: null, note: `ls-remote failed: ${r.err}` };
	const tags = r.out
		.split("\n")
		.map((l) => l.split("\t")[1] ?? "")
		.filter((ref) => ref.startsWith("refs/tags/") && !ref.endsWith("^{}"))
		.map((ref) => ref.slice(10));
	if (tags.length === 0) return { tag: null, note: "no tags on the remote" };
	const versions = tags.filter((t) => /^v?\d+(\.\d+)+/.test(t));
	const skipped = tags.length - versions.length;
	if (versions.length === 0) return { tag: null, note: `${tags.length} tag(s) on origin, none version-like (e.g. ${tags.slice(0, 3).join(", ")})` };
	const key = (t) => t.replace(/^v/, "").split(/[.\-_+]/).map((p) => (/^\d+$/.test(p) ? Number(p) : p));
	const cmp = (a, b) => {
		const A = key(a), B = key(b);
		for (let i = 0; i < Math.max(A.length, B.length); i++) {
			const x = A[i] ?? -Infinity, y = B[i] ?? -Infinity;
			if (x === y) continue;
			if (typeof x === typeof y) return x > y ? 1 : -1;
			return typeof x === "number" ? 1 : -1; // a numeric segment outranks a prerelease label
		}
		return 0;
	};
	return { tag: versions.sort(cmp).at(-1), note: `highest of ${versions.length} version-like tag(s)${skipped ? `; ${skipped} non-version tag(s) skipped (e.g. ${tags.filter((t) => !versions.includes(t)).slice(0, 2).join(", ")})` : ""} — \`git -C ${cloneRel} ls-remote --tags origin\`` };
}

/**
 * Manifest versions are printed but never trusted — the three counter-examples are in `docs/SELFDEV.md`.
 */
function manifestVersions(cloneRel) {
	const out = [];
	const abs = join(ROOT, cloneRel);
	const read = (rel) => {
		try {
			return readFileSync(join(abs, rel), "utf8");
		} catch {
			return null;
		}
	};
	const pkg = read("package.json");
	if (pkg) {
		try {
			const j = JSON.parse(pkg);
			out.push(`package.json ${JSON.stringify(j.version ?? null)}${j.name ? ` (name ${JSON.stringify(j.name)})` : ""}`);
		} catch {
			out.push("package.json UNPARSEABLE");
		}
	}
	const py = read("pyproject.toml");
	if (py) {
		const m = py.match(/^version\s*=\s*["']([^"']*)["']/m);
		const name = py.match(/^name\s*=\s*["']([^"']*)["']/m);
		out.push(`pyproject.toml ${m ? JSON.stringify(m[1]) : "no top-level version"}${name ? ` (name ${JSON.stringify(name[1])})` : ""}`);
	}
	return out.length ? out.join("; ") : "no root manifest read";
}

function pin(cloneRel, { tags }) {
	const sha = git(["-C", cloneRel, "rev-parse", "HEAD"]);
	if (!sha.ok) return { clone: cloneRel, error: `not a git clone: ${sha.err}` };
	const date = git(["-C", cloneRel, "log", "-1", "--format=%cI"]);
	const shallow = git(["-C", cloneRel, "rev-parse", "--is-shallow-repository"], { allowFail: true });
	const lic = detectLicense(cloneRel);
	const tag = tags ? latestTag(cloneRel) : { tag: null, note: "not fetched — rerun with --tags" };
	const remote = git(["-C", cloneRel, "remote", "get-url", "origin"], { allowFail: true });
	return {
		name: cloneRel.split("/").pop(),
		clone: cloneRel,
		remote: remote.ok ? remote.out : null,
		sha: sha.out,
		short: sha.out.slice(0, 8),
		date: date.ok ? date.out : "?",
		shallow: shallow.out === "true",
		license: lic.id,
		licenseEvidence: lic.evidence,
		licenseNote: lic.note,
		tag: tag.tag,
		tagNote: tag.note,
		manifest: manifestVersions(cloneRel),
		commands: [
			`git -C ${cloneRel} rev-parse HEAD`,
			`git -C ${cloneRel} log -1 --format=%cI`,
			`git -C ${cloneRel} rev-parse --is-shallow-repository`,
			`cat ${lic.evidence ?? cloneRel}  # licence signature`,
			`git -C ${cloneRel} ls-remote --tags origin   # tag`,
		],
	};
}

function table(pins) {
	const head = "| project | pinned HEAD | commit date | license | shallow | latest remote tag | manifest version (UNRELIABLE) | maturity (judge, do not infer) |";
	const rows = pins.map((p) =>
		p.error
			? `| \`${p.clone}\` | ERROR | | | | | | ${p.error} |`
			: `| \`${p.name}\` | \`${p.short}\` | ${p.date} | ${p.license}${p.licenseEvidence ? ` (\`${p.licenseEvidence}\`)` : ""} | ${p.shallow} | ${p.tag ? `\`${p.tag}\`` : `_not fetched_`} | ${p.manifest} | _<judge: activity, and whether its spec runs ahead of its code>_ |`,
	);
	return [head, "|---|---|---|---|---|---|---|---|", ...rows].join("\n");
}

/** The Do 2 header block for `docs/reviews/<name>-review.md` — nothing transcribed by hand. */
function header(p) {
	if (p.error) return `cannot pin ${p.clone}: ${p.error}`;
	return [
		`**Pinned HEAD:** \`${p.sha}\` (short \`${p.short}\`) · **commit date:** ${p.date} · **license:** ${p.license}` +
			`${p.licenseEvidence ? ` (read \`${p.licenseEvidence}\`; ${p.licenseNote})` : ` — ${p.licenseNote}`} · **shallow clone:** ${p.shallow}${p.shallow ? " (a re-review needs `git fetch --unshallow origin` in place — do not delete the clone)" : ""} · **latest remote tag:** ${p.tag ? `\`${p.tag}\`` : `_none read_`} (${p.tagNote}) · **maturity:** _<judge — activity from the commit date, and whether the spec runs ahead of the code>_ · **operator's question:** _<state it>`,
		`**Manifest versions (UNRELIABLE — cite the tag and the commit date, never these):** ${p.manifest}`,
		`**Reproduce every field above with:**`,
		"```bash",
		...p.commands,
		"```",
	].join("\n");
}

/**
 * The two rules `docs/runbooks/competitor-review.md` proposes for `check` (`competitor-review-covered`,
 * ROADMAP 81/82), run here as an audit so the runbook has a Verify command that actually executes:
 *  (a) a review whose clone exists must have a `docs/COMPETITORS.md` entry;
 *  (b) a review that cites a clone must cite THAT clone's current HEAD — a review whose pin is not its
 *      clone's HEAD is a stale review.
 * Keying on the clone's existence avoids flagging non-competitor reviews under `docs/reviews/`. A review whose
 * clone is gone is a NOTE, not a failure: its pin is then the only record, and that is exactly what the
 * generated table exists to stop being true.
 *
 * The sha floor is 8 (`docs/SELFDEV.md`: `src/citation.mjs` uses /\b[0-9a-f]{8,40}\b/ and so never sees a
 * 7-char sha) — published here with the result, per D142.
 */
function reviewAudit(pins) {
	const dir = join(ROOT, "docs", "reviews");
	if (!existsSync(dir)) return { problems: [], notes: ["docs/reviews/ does not exist"] };
	const competitors = existsSync(join(ROOT, "docs", "COMPETITORS.md")) ? readFileSync(join(ROOT, "docs", "COMPETITORS.md"), "utf8") : "";
	const problems = [];
	const notes = [];
	for (const name of readdirSync(dir).filter((f) => f.endsWith("-review.md"))) {
		const text = readFileSync(join(dir, name), "utf8");
		const cited = [...new Set([...text.matchAll(/vendor\/eval\/([A-Za-z0-9._-]+)/g)].map((m) => m[1]))];
		for (const proj of cited) {
			const p = pins.find((x) => x.name === proj && !x.error);
			if (!p) {
				notes.push(`docs/reviews/${name} cites vendor/eval/${proj}, which is not a clone on this machine — the sha in the review is the only record of its pin, and it is not covered by ${DEFAULT_TABLE}`);
				continue;
			}
			if (!text.includes(p.sha) && !text.includes(p.short)) problems.push(`docs/reviews/${name} cites vendor/eval/${proj} but does not name that clone's HEAD ${p.sha} (short ${p.short}) — the review is pinned to something the clone no longer holds, or was never pinned`);
			if (competitors && !competitors.includes(proj)) problems.push(`docs/reviews/${name} reviews ${proj} (clone present) but docs/COMPETITORS.md has no entry for it — competitor-review.md Do 7`);
		}
	}
	return { problems, notes, shaFloor: 8 };
}

/** Is a path tracked / ignored? The whole point of the tool is that the pins be in git. */
function trackedness(path) {
	// Raw statuses, not the `git()` wrapper: `ls-files --error-unmatch` and `check-ignore -q` both signal by
	// EXIT CODE, and a wrapper that swallows non-zero status reports an untracked pin file as tracked (measured:
	// `git ls-files --error-unmatch docs/VENDOR-PINS.md` exits 1 for a file that is only on disk).
	const inIndex = spawnSync("git", ["ls-files", "--error-unmatch", path], { cwd: ROOT, encoding: "utf8" });
	const ignored = spawnSync("git", ["check-ignore", "-q", path], { cwd: ROOT, encoding: "utf8" });
	return { tracked: inIndex.status === 0, ignored: ignored.status === 0 };
}

const TABLE_NOTES = [
	"**How to read this table.** It is generated from the live clones; regenerate it with the command at the top of the file and never hand-edit between the markers.",
	 "`pinned HEAD` and `commit date` come from `git -C <clone> rev-parse HEAD` and `log -1 --format=%cI`; `license` is read out of the clone's own `LICENSE`/`COPYING` file (evidence path in the cell), never from a badge; `latest remote tag` is the highest **version-like** tag on `origin` via `git -C <clone> ls-remote --tags origin` — a bare `tail -1` is ref order, and picks labels like `nightly`.",
	"`manifest version` is printed because it is a trap, not because it is evidence — cite the tag and the commit date. `maturity` is a judgement the tool refuses to make.",
];

function generatedBlock(pins, argLine) {
	// The volatile columns get a timestamp; the pin columns do not need one, because they cannot move.
	// `--check` compares ROWS, so this line can never make a check fail.
	const observed = "**Observed at:** " + new Date().toISOString() + " — `latest remote tag` and `manifest version` are upstream state at that instant and will drift (a NOTE, not a failure). `pinned HEAD`, `commit date`, `license` and `shallow` describe the PIN and must not move.";
	return [BEGIN(argLine), "", observed, "", table(pins), "", TABLE_NOTES.join("\n\n"), "", END].join("\n");
}

function spliceBlock(existing, block) {
	const m = existing.match(BEGIN_RE);
	if (!m) return `${existing.trimEnd()}\n\n${block}\n`;
	const start = m.index;
	const end = existing.indexOf(END, start);
	if (end < 0) return `${existing.slice(0, start)}${block}\n`;
	return `${existing.slice(0, start)}${block}${existing.slice(end + END.length)}`;
}

function main(argv) {
	const opts = parseArgs(argv);
	if (opts.help) {
		process.stdout.write(`${USAGE}\n`);
		return 0;
	}
	const clones = discoverClones(opts.clones);
	const matches = (c) => opts.projects.some((p) => c === `${opts.clones}/${p}` || c.endsWith(`/${p}`));
	const selected = opts.projects.length ? clones.filter(matches) : clones;
	if (opts.projects.length && selected.length === 0) throw new UsageError(`no clone matches --project ${opts.projects.join(" --project ")} under ${opts.clones}/ (found: ${clones.join(", ") || "none"})`);
	if (selected.length === 0) throw new UsageError(`no git clones under ${opts.clones}/ — clone first per docs/runbooks/competitor-review.md Do 1`);

	const pins = selected.map((c) => pin(c, { tags: opts.tags }));

	if (opts.check) {
		const path = opts.checkPath;
		const abs = join(ROOT, path);
		const problems = [];
		const driftNotes = [];
		const t = trackedness(path);
		if (!existsSync(abs)) problems.push(`${path} does not exist — run: node tools/vendor-pins.mjs --write ${path}`);
		else {
			if (!t.tracked) problems.push(`${path} is NOT TRACKED by git${t.ignored ? " and IS gitignored" : ""} — the pins are untracked evidence, which is the failure this tool exists to prevent`);
			const text = readFileSync(abs, "utf8");
			const m = text.match(BEGIN_RE);
			if (!m) problems.push(`${path} has no generated block — the table there is hand-typed and cannot be diffed`);
			else {
				const recordedArgs = m[1].trim();
				// Re-run with the RECORDED flags, so a table that was built with --tags is re-checked against the network.
				const rerunOpts = { tags: /--tags/.test(recordedArgs) };
				const fresh = selected.map((c) => pin(c, rerunOpts));
				const want = generatedBlock(fresh, recordedArgs);
				const have = text.slice(m.index, text.indexOf(END, m.index) + END.length);
				if (want.replace(BEGIN_RE, "") !== have.replace(BEGIN_RE, "")) {
					// Name the drifted COLUMN by its header text, so the message says what moved rather than
					// making the reader diff a seven-row table.
					const headerCells = (s) => (s.split("\n").find((l) => l.startsWith("| project")) ?? "").split("|").map((c) => c.trim());
					const rowsOf = (s) => s.split("\n").filter((l) => l.startsWith("| `")).map((l) => l.split("|").map((c) => c.trim()));
					const cols = headerCells(want);
					const A = new Map(rowsOf(have).map((r) => [r[1], r]));
					// Which columns are ALLOWED to move decides whether a difference is a failure at all. HEAD, commit
					// date, licence and shallow-ness are properties of the PIN: if one moved, the recorded review
					// evidence is wrong — FAIL. The remote tag and the manifest version are properties of upstream
					// right now, and they move hourly (measured: `prime-agent` published `v0.10.2-beta.15` between two
					// runs of this tool ~30 minutes apart) — a NOTE with a regen hint, never a red check that trains
					// people to ignore red checks.
					const PIN_COLS = new Set([2, 3, 4, 5]);
					const OBS_COLS = new Set([6, 7]);
					for (const r of rowsOf(want)) {
						const old = A.get(r[1]);
						if (!old) problems.push(`pin table is missing a row for ${r[1]}`);
						else if (old[2] !== r[2]) problems.push(`${r[1]}: the PIN moved — the table says HEAD ${old[2]}, the clone says ${r[2]}. A re-review diffs ${old[2]}..${r[2]} (per competitor-review.md prompt 3); it does not re-derive the whole review.`);
						else for (let i = 3; i < Math.min(old.length, r.length); i++) {
							if (old[i] === r[i]) continue;
							const what = `${r[1]}: "${cols[i] ?? `column ${i - 1}`}" says ${old[i]}, the clone says ${r[i]}`;
							if (PIN_COLS.has(i)) problems.push(`${what} — a pin column must not move`);
							else if (OBS_COLS.has(i)) driftNotes.push(`${what} — upstream state, not the pin; regenerate when convenient`);
						}
					}
					for (const name of A.keys()) if (!rowsOf(want).some((r) => r[1] === name)) problems.push(`pin table has a row for ${name}, which is no longer a clone under ${opts.clones}/`);
				}
			}
		}
		const audit = reviewAudit(pins);
		problems.push(...audit.problems);
		for (const n of audit.notes) process.stdout.write(`  NOTE ${n}\n`);
		for (const n of driftNotes) process.stdout.write(`  DRIFT NOTE ${n}\n`);
		if (problems.length) {
			process.stdout.write(`PIN CHECK FAIL (${path}) — ${problems.length} problem(s):\n${problems.map((p) => `  - ${p}`).join("\n")}\n`);
			process.stdout.write(`regen: node tools/vendor-pins.mjs --write ${path}  (then commit it — an uncommitted pin is an un-pinned review)\n`);
			return 1;
		}
		process.stdout.write(`PIN CHECK PASS (${path}): ${pins.length} clone(s), every row matches its clone's HEAD/date/licence, the table is tracked by git, and ${pins.length} clone(s) pass the review audit (a review naming a present clone cites its HEAD and has a COMPETITORS entry).\n`);
		return 0;
	}

	if (opts.format === "json") {
		process.stdout.write(`${JSON.stringify({ pins, generatedAt: new Date().toISOString() }, null, 2)}\n`);
		return 0;
	}
	if (opts.format === "header") {
		if (pins.length > 1 && !opts.write) process.stdout.write(`(emitting ${pins.length} headers; use --project <name> for one)\n`);
		process.stdout.write(`${pins.map(header).join("\n\n---\n\n")}\n`);
		return 0;
	}
	if (opts.write) {
		const argLine = ["--write", opts.write, opts.tags ? "--tags" : null].filter(Boolean).join(" ");
		const t = trackedness(opts.write);
		if (t.ignored) throw new UsageError(`refusing to write pins to ${opts.write}: it is gitignored — pins written there are invisible to the next session (that is the failure this tool exists to prevent)`);
		const block = generatedBlock(pins, argLine);
		const existing = existsSync(join(ROOT, opts.write)) ? readFileSync(join(ROOT, opts.write), "utf8") : "";
		writeFileSync(join(ROOT, opts.write), spliceBlock(existing, block), "utf8");
		process.stdout.write(`wrote ${pins.length} pin(s) to ${opts.write} between the generated markers (tracked: ${t.tracked} — if false, git add it)\n`);
		if (!t.tracked) process.stdout.write(`  NOTE: ${opts.write} is not tracked yet. A pin in an UNTRACKED file is the same failure as a pin in an ignored one.\n`);
		return 0;
	}
	process.stdout.write(`${table(pins)}\n`);
	return 0;
}

try {
	process.exitCode = main(process.argv.slice(2));
} catch (e) {
	if (e instanceof UsageError) process.stderr.write(`${e.message}\n${USAGE}\n`);
	else process.stderr.write(`${e?.stack ?? e}\n`);
	process.exitCode = 2;
}
